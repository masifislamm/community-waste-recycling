"""Generate Appendix A (unit test results) for the report.

Reads the JUnit XML reports that Maven Surefire writes to target/surefire-reports/
and writes docs/appendix-a-unit-tests.md as a Markdown table in Template 2 form:
ID, Class, Method, Input/Scenario, Expected, Actual, Status.

Test names follow methodName_scenario_expectedBehaviour, so each name is split
into the Method, Input/Scenario and Expected columns.

Usage (from the project folder, after the tests have run):
    mvn -B verify
    python scripts/gen-appendix-a.py
"""

import re
import sys
import xml.etree.ElementTree as ElementTree
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent.parent
REPORTS_DIR = PROJECT_ROOT / "target" / "surefire-reports"
OUTPUT_FILE = PROJECT_ROOT / "docs" / "appendix-a-unit-tests.md"

HEADER = [
    "# Appendix A: Unit test results",
    "",
    "Generated by `scripts/gen-appendix-a.py` from the Surefire reports of the last `mvn verify` run.",
    "Parameterized tests appear once per input (case number in the Input/Scenario column).",
    "",
    "| ID | Class | Method | Input/Scenario | Expected | Actual | Status |",
    "|---|---|---|---|---|---|---|",
]


def words(camel_case):
    """Turn 'status500WithCache' into 'status 500 with cache'."""
    spaced = re.sub(r"(?<=[a-z])(?=[A-Z0-9])|(?<=[0-9])(?=[A-Za-z])", " ", camel_case)
    return spaced.lower()


def split_test_name(name):
    """Split 'method_scenario_expected(int)[2]' into method, scenario and expected text."""
    case = re.search(r"\[(\d+)\]$", name)
    base = name.split("(")[0]
    parts = base.split("_")
    if len(parts) != 3:
        return base, "", ""
    method, scenario, expected = parts
    scenario_text = words(scenario)
    if case:
        scenario_text += f" (case {case.group(1)})"
    return method, scenario_text, words(expected)


def result_of(testcase):
    """Return the Actual and Status columns for one <testcase> element."""
    for tag, status in (("failure", "Fail"), ("error", "Error"), ("skipped", "Skipped")):
        problem = testcase.find(tag)
        if problem is not None:
            message = (problem.get("message") or tag).splitlines()[0]
            return message.replace("|", "/"), status
    return "As expected", "Pass"


def rows_from(report_file):
    """Yield one table row (without ID) per test case in a Surefire XML report."""
    suite = ElementTree.parse(report_file).getroot()
    for testcase in suite.iter("testcase"):
        class_name = testcase.get("classname", "").split(".")[-1]
        method, scenario, expected = split_test_name(testcase.get("name", ""))
        actual, status = result_of(testcase)
        yield [class_name, method, scenario, expected, actual, status]


def main():
    report_files = sorted(REPORTS_DIR.glob("TEST-*.xml"))
    if not report_files:
        sys.exit(f"No test reports found in {REPORTS_DIR}. Run 'mvn -B verify' first.")
    rows = [row for report in report_files for row in rows_from(report)]
    lines = list(HEADER)
    for number, row in enumerate(rows, start=1):
        lines.append("| " + " | ".join([f"UT-{number:02d}"] + row) + " |")
    passed = sum(1 for row in rows if row[-1] == "Pass")
    lines += ["", f"**Total:** {len(rows)} test cases, {passed} passed."]
    OUTPUT_FILE.parent.mkdir(exist_ok=True)
    OUTPUT_FILE.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {len(rows)} rows to {OUTPUT_FILE}")


if __name__ == "__main__":
    main()
